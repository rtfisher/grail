"""Real trained-network feedback and independent coupled-state regressions."""
from copy import deepcopy
from pathlib import Path

import numpy as np
import pytest
import torch

from atmosphere.twolevel.diagnostics import SourceProblem, truth_source, validated_atmosphere
from emulator.twolevel.full_envelope.structured import (
    load_structured_checkpoint, make_structured_adapter, save_structured_checkpoint,
)
from grail import resolvent_solve

ROOT = Path(__file__).resolve().parents[4]
ARTIFACTS = ROOT/"examples/data/structured"


@pytest.fixture(scope="module")
def trained():
    model, _ = load_structured_checkpoint(ARTIFACTS/"model.pt")
    return model


def test_trained_rates_on_independent_offline_labels(trained):
    data = np.load(ARTIFACTS/"training.npz")
    index = data["test_indices"]
    parameters = torch.from_numpy(10.**data["inputs_log10"][index])
    with torch.no_grad():
        probability, thermal = trained.coefficients(*parameters.T)
    labels = data["labels"][index]
    probability_target = torch.sigmoid(torch.logit(parameters[:, 2])+torch.from_numpy(labels[:, 1]))
    thermal_target = trained.Bstar*np.exp(labels[:, 0])
    assert np.max(np.abs(thermal.numpy()/thermal_target-1)) < 1e-4
    assert np.max(np.abs(probability.numpy()/probability_target.numpy()-1)) < 2e-5


def test_inference_and_jvp_do_not_call_reference_physics(trained, monkeypatch):
    import atmosphere.twolevel.rate_equations as reference
    import atmosphere.twolevel.diagnostics as diagnostics

    def forbidden(*args, **kwargs):
        raise AssertionError("reference physics was called during NN inference")

    monkeypatch.setattr(reference, "rate_equation_solve", forbidden)
    monkeypatch.setattr(diagnostics, "truth_source", forbidden)
    monkeypatch.setattr(diagnostics, "planck_array", forbidden)
    adapter = make_structured_adapter(trained, 1e-4)
    J = torch.tensor([1e-12, 1e-10, 1e-9], dtype=torch.float64)
    T, ne = torch.full_like(J, 8000), torch.full_like(J, 1e12)
    populations, tangent = torch.func.jvp(lambda x: adapter(x, T, ne), (J,), (J,))
    assert torch.isfinite(populations).all() and torch.isfinite(tangent).all()
    assert torch.all(populations > 0)
    assert torch.all(populations[:, 1] < .5)
    torch.testing.assert_close(populations.sum(-1), torch.ones_like(J), rtol=0, atol=1e-15)


def test_learned_thermal_weights_change_predictions(trained):
    changed = deepcopy(trained)
    with torch.no_grad():
        changed.thermal_linear.bias.add_(np.log(1.1))
    x = torch.tensor([[-18, np.log10(8000), 12, -2]], dtype=torch.float64)
    original = trained(x)[0, 1]
    altered = changed(x)[0, 1]
    assert altered/original > 1.09


def test_checkpoint_round_trip_and_legacy_rejection(trained, tmp_path):
    path = tmp_path/"model.pt"
    save_structured_checkpoint(path, trained, test="round trip")
    loaded, metadata = load_structured_checkpoint(path)
    x = torch.tensor([[-12, np.log10(6000), 10, -6]], dtype=torch.float64)
    assert torch.equal(loaded(x), trained(x))
    assert metadata == {"test": "round trip"}
    torch.save({"version": "incompatible-model"}, path)
    with pytest.raises(ValueError, match="not a structured"):
        load_structured_checkpoint(path)


def test_actual_neural_jvp_matches_positive_domain_differences(trained):
    atm = validated_atmosphere(T0=12000, epsilon=1e-6, n_tau=12)
    problem = SourceProblem(atm, make_structured_adapter(trained, 1e-6))
    source = truth_source(atm, problem.transfer)
    q = problem.populations(source)
    direction = q*np.random.default_rng(314159).uniform(-.5, .5, len(q))
    h = 1e-3
    assert np.all(q-h*direction > 0)
    difference = (problem.population_cycle(q+h*direction)-
                  problem.population_cycle(q-h*direction))/(2*h)
    tangent = problem.population_jacobian(q)@direction
    assert np.linalg.norm(difference-tangent)/np.linalg.norm(tangent) < 1e-7


@pytest.mark.parametrize("T,epsilon,tau", [
    (T, eps, tau) for T in [6000., 12000.] for eps in [1e-2, 1e-6]
    for tau in [1e2, 1e4]
])
def test_full_replacement_predicts_independently_solved_shift(trained, T, epsilon, tau):
    atm = validated_atmosphere(T0=T, ne0=1e12, epsilon=epsilon, tau_max=tau)
    problem = SourceProblem(atm, make_structured_adapter(trained, epsilon))
    st = truth_source(atm, problem.transfer)
    qt = problem.populations(st)
    with torch.no_grad():
        probability, thermal = problem.adapter.model.coefficients(
            atm.T, atm.n_e, torch.full_like(atm.T, epsilon))
    p, B = probability.numpy(), thermal.numpy()
    # The target is a separate equilibrium solve using learned coefficients.
    # It is not generated by GRAIL or by applying its matrix to a chosen shift.
    se = np.linalg.solve(np.eye(len(st))-(1-p)[:, None]*problem.L,
                        (1-p)*problem.b+p*B/problem.B0)
    qe = problem.populations(se)
    actual = qe-qt
    solved = problem.solve()
    assert solved["converged"]
    assert np.max(np.abs(solved["source"]/se-1)) < 1e-7
    assert np.max(np.abs(qe/qt-1)) < 1e-3
    assert np.max(np.abs(problem.population_cycle(qe)-qe)/qe) < 1e-9
    residual = problem.population_cycle(qe)-problem.population_cycle(qe, 0)
    J = torch.from_numpy((problem.L@se+problem.b)*problem.B0).requires_grad_(True)
    qout = problem.adapter(J, atm.T, atm.n_e)[:, 1]
    dnn_dJ = torch.autograd.grad(qout.sum(), J)[0].detach().numpy()
    host = problem.Bstar*problem.L/(1-2*qe)[None, :]**2
    K = problem.population_jacobian(qe)
    np.testing.assert_allclose(dnn_dJ[:, None]*host, K, rtol=1e-11, atol=1e-14)
    result = resolvent_solve(qe, residual,
        emulator_jvp=lambda v: dnn_dJ*np.asarray(v),
        host_jvp=lambda v: host@np.asarray(v),
        gmres_tol=1e-11, gmres_maxiter=300)
    prediction = np.asarray(result.delta_x_star)
    assert np.linalg.norm((np.eye(len(K))-K)@prediction-residual)/np.linalg.norm(residual) < 1e-8
    assert np.linalg.norm(prediction-actual)/np.linalg.norm(actual) < 1e-2
    # Broken feedback must fail the same independently determined target.
    bad = resolvent_solve(qe, residual,
        emulator_jvp=lambda v: np.zeros_like(np.asarray(v)),
        host_jvp=lambda v: host@np.asarray(v))
    assert np.linalg.norm(np.asarray(bad.delta_x_star)-actual)/np.linalg.norm(actual) > .1
